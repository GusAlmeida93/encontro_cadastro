MESAS = [(str(n), str(n)) for n in range(1, 58)]


def _choices(names):
    return [(name, name) for name in sorted(set(names), key=str.casefold)]


def hora_atual():
    """Current time in settings.TIME_ZONE, to the second."""
    return timezone.localtime().time().replace(microsecond=0)


class Cadastro(models.Model):
    mesa = models.CharField(max_length=2, choices=MESAS)
    associado = models.CharField(
        max_length=50,
        choices=_choices(REDES + INDUSTRIAS + DISTRIBUIDORES + PARCEIROS),
    )
    rede = models.CharField(max_length=50, choices=_choices(REDES))
    dia = models.DateField(default=timezone.localdate)
    hora = models.TimeField(default=hora_atual)

    def __str__(self):
        return f"{self.associado} - {self.rede}"
